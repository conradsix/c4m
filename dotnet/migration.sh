#!/usr/bin/env bash
set -euo pipefail

# Adds, removes and applies the engine's migrations. The sample host is the startup project, and the database is the
# repo's docker-compose one unless C4M_CONNECTION_STRING says otherwise.
#
# Usage:
#   ./migration.sh add -n <MigrationName>   # letters only
#   ./migration.sh remove                   # removes the last migration
#   ./migration.sh update                   # applies every migration
#   ./migration.sh rollback                 # reverts the last applied migration

if [[ $# -lt 1 ]]; then
  echo "Usage: $0 {add -n <MigrationName>|remove|update|rollback}" >&2
  exit 1
fi

command=$1
shift

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd "$repo_root"

project="src/ConradSix.C4M"
startup_project="samples/ConradSix.C4M.SampleHost"
output_dir="Data/Migrations"
ef=(dotnet ef --project "$project" --startup-project "$startup_project" --configuration Debug)

dotnet tool restore > /dev/null

case $command in
  add)
    migration_name=""
    while getopts ":n:" opt; do
      case $opt in
        n) migration_name=$OPTARG ;;
        *)
          echo "Usage: $0 add -n <MigrationName>" >&2
          exit 1
          ;;
      esac
    done

    if [[ ! $migration_name =~ ^[a-zA-Z]+$ ]]; then
      echo "The migration name must be letters only." >&2
      exit 1
    fi

    "${ef[@]}" migrations add "$migration_name" --output-dir "$output_dir"

    # Generated code is exempt from the analyzers.
    migration_file=$(find "$project/$output_dir" -name "*_$migration_name.cs")
    sed -i '1s/^\xEF\xBB\xBF//; 1s/^/\/\/ <auto-generated \/>\n\n/' "$migration_file"
    echo "Added $migration_file"
    ;;

  remove)
    "${ef[@]}" migrations remove
    ;;

  update)
    "${ef[@]}" database update
    ;;

  rollback)
    mapfile -t migrations < <("${ef[@]}" migrations list --no-color 2> /dev/null | grep -oE '^[0-9]{14}_[A-Za-z0-9_]+')
    if [[ ${#migrations[@]} -lt 2 ]]; then
      "${ef[@]}" database update 0
    else
      "${ef[@]}" database update "${migrations[-2]}"
    fi
    ;;

  *)
    echo "Unknown command '$command'. Use add, remove, update or rollback." >&2
    exit 1
    ;;
esac
