namespace ConradSix.C4M.Tests.Endpoints.Page;

using AwesomeAssertions;

using ConradSix.C4M.Data;
using ConradSix.C4M.Data.Model;

using Microsoft.Extensions.DependencyInjection;

[Collection(C4MAppCollection.Name)]
public sealed class PathTriggerTests(C4MAppFixture fixture) :
    IAsyncDisposable
{
    [Fact]
    public async Task Path_ShouldBeAutoGenerated_WhenPageIsCreated()
    {
        // Arrange
        await using var scope = fixture.Services.CreateAsyncScope();
        var context = scope.ServiceProvider.GetRequiredService<CmsEngineDbContext>();

        var realtorId = Guid.NewGuid();

        // Create a root page
        var rootPage = new PageEntity
        {
            Slug = "about",
            ParentId = null,
        };

        // Act
        context.Pages.Add(rootPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Assert
        rootPage.Path.Should().Be("/about");
    }

    [Fact]
    public async Task Path_ShouldBeHierarchical_ForNestedPages()
    {
        // Arrange
        await using var scope = fixture.Services.CreateAsyncScope();
        var context = scope.ServiceProvider.GetRequiredService<CmsEngineDbContext>();

        var realtorId = Guid.NewGuid();

        // Create parent page
        var parentPage = new PageEntity
        {
            Slug = "about",
            ParentId = null,
        };

        context.Pages.Add(parentPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Create child page
        var childPage = new PageEntity
        {
            Slug = "team",
            ParentId = parentPage.Id,
        };

        // Act
        context.Pages.Add(childPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Assert
        childPage.Path.Should().Be("/about/team");
    }

    [Fact]
    public async Task Path_ShouldUpdateAutomatically_WhenSlugChanges()
    {
        // Arrange
        await using var scope = fixture.Services.CreateAsyncScope();
        var context = scope.ServiceProvider.GetRequiredService<CmsEngineDbContext>();

        var realtorId = Guid.NewGuid();

        var page = new PageEntity
        {
            Slug = "about",
            ParentId = null,
        };

        context.Pages.Add(page);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        page.Path.Should().Be("/about");

        // Act - Change the slug
        page.Slug = "company";
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Assert
        page.Path.Should().Be("/company");
    }

    [Fact]
    public async Task ChildPaths_ShouldUpdateAutomatically_WhenParentSlugChanges()
    {
        // Arrange
        await using var scope = fixture.Services.CreateAsyncScope();
        var context = scope.ServiceProvider.GetRequiredService<CmsEngineDbContext>();

        var realtorId = Guid.NewGuid();

        // Create parent and child pages
        var parentPage = new PageEntity
        {
            Slug = "about",
            ParentId = null,
        };

        context.Pages.Add(parentPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        var childPage = new PageEntity
        {
            Slug = "team",
            ParentId = parentPage.Id,
        };

        context.Pages.Add(childPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Verify initial paths
        parentPage.Path.Should().Be("/about");
        childPage.Path.Should().Be("/about/team");

        // Act - Change parent slug
        parentPage.Slug = "company";
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Refresh both pages from database to get trigger-updated paths
        await context.Entry(childPage).ReloadAsync(TestContext.Current.CancellationToken);

        // Assert - Both paths should update
        parentPage.Path.Should().Be("/company");
        childPage.Path.Should().Be("/company/team");
    }

    [Fact]
    public async Task ComplexNestedHierarchy_ShouldMaintainPaths_WithAddsAndUpdates()
    {
        // Arrange
        await using var scope = fixture.Services.CreateAsyncScope();
        var context = scope.ServiceProvider.GetRequiredService<CmsEngineDbContext>();

        var realtorId = Guid.NewGuid();

        // Create a complex hierarchy: /about -> /about/company -> /about/company/leadership -> /about/company/leadership/ceo
        var aboutPage = new PageEntity
        {
            Slug = "about",
            ParentId = null,
        };

        context.Pages.Add(aboutPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        var companyPage = new PageEntity
        {
            Slug = "company",
            ParentId = aboutPage.Id,
        };

        context.Pages.Add(companyPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        var leadershipPage = new PageEntity
        {
            Slug = "leadership",
            ParentId = companyPage.Id,
        };

        context.Pages.Add(leadershipPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        var ceoPage = new PageEntity
        {
            Slug = "ceo",
            ParentId = leadershipPage.Id,
        };

        context.Pages.Add(ceoPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Verify initial hierarchy paths
        aboutPage.Path.Should().Be("/about");
        companyPage.Path.Should().Be("/about/company");
        leadershipPage.Path.Should().Be("/about/company/leadership");
        ceoPage.Path.Should().Be("/about/company/leadership/ceo");

        // Act 1: Change middle-level slug - should cascade to all children
        companyPage.Slug = "our-company";
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Refresh all affected pages
        await context.Entry(leadershipPage).ReloadAsync(TestContext.Current.CancellationToken);
        await context.Entry(ceoPage).ReloadAsync(TestContext.Current.CancellationToken);

        // Assert after first update
        aboutPage.Path.Should().Be("/about");
        companyPage.Path.Should().Be("/about/our-company");
        leadershipPage.Path.Should().Be("/about/our-company/leadership");
        ceoPage.Path.Should().Be("/about/our-company/leadership/ceo");

        // Act 2: Add a new sibling to CEO page
        var ctoPage = new PageEntity
        {
            Slug = "cto",
            ParentId = leadershipPage.Id,
        };

        context.Pages.Add(ctoPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Assert new page has correct path
        ctoPage.Path.Should().Be("/about/our-company/leadership/cto");

        // Act 3: Move CEO page to be under the root (change parent)
        ceoPage.ParentId = aboutPage.Id;
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Assert after restructuring
        ceoPage.Path.Should().Be("/about/ceo");

        // CTO should remain unchanged
        ctoPage.Path.Should().Be("/about/our-company/leadership/cto");

        // Act 4: Add a grandchild under the moved CEO page
        var bioPage = new PageEntity
        {
            Slug = "bio",
            ParentId = ceoPage.Id,
        };

        context.Pages.Add(bioPage);
        await context.SaveChangesAsync(TestContext.Current.CancellationToken);

        // Assert final hierarchy
        bioPage.Path.Should().Be("/about/ceo/bio");

        // Verify all final paths are correct
        aboutPage.Path.Should().Be("/about");
        companyPage.Path.Should().Be("/about/our-company");
        leadershipPage.Path.Should().Be("/about/our-company/leadership");
        ctoPage.Path.Should().Be("/about/our-company/leadership/cto");
        ceoPage.Path.Should().Be("/about/ceo");
        bioPage.Path.Should().Be("/about/ceo/bio");
    }

    public ValueTask DisposeAsync() => fixture.TearDownTestAsync();
}
